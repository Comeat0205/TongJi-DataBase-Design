  '演示会员',
  '13800000001',
  '普通',
  'M',
  SYSDATE,
  '1',
  (SELECT USER_ID FROM USERS WHERE LOGIN_NAME = 'demo_member')
FROM dual
WHERE EXISTS (SELECT 1 FROM USERS WHERE LOGIN_NAME = 'demo_member')
AND NOT EXISTS (
  SELECT 1 FROM MEMBER WHERE USER_ID = (SELECT USER_ID FROM USERS WHERE LOGIN_NAME = 'demo_member')
);

