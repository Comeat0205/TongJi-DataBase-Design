-- MEMBER.USER_ID 有唯一约束 UK_MEMBER_USER_ID：一个账号只能绑一名会员。

-- 1) 演示会员账号 demo_member
INSERT INTO USERS (
  USER_ID, LOGIN_NAME, PASSWORD_HASH, DISPLAY_NAME, STATUS, CREATED_AT, UPDATED_AT
)
SELECT
  NVL((SELECT MAX(USER_ID) FROM USERS), 0) + 1,
  'demo_member',
  '$2b$10$Tcc8wGAAKY.tiAUwrdBBqet5fz3eIWIwmFs54GT50TgZ7f3L6pl6a',
  '演示会员',
  '1',
  SYSDATE,
  SYSDATE
FROM dual
WHERE NOT EXISTS (
  SELECT 1 FROM USERS WHERE LOGIN_NAME = 'demo_member'
);

-- 优先：把尚未绑定账号的会员绑到 demo_member（仅当该账号尚未绑定任何人）
UPDATE MEMBER
SET USER_ID = (SELECT USER_ID FROM USERS WHERE LOGIN_NAME = 'demo_member')
WHERE MEMBER_ID = (
  SELECT MIN(m.MEMBER_ID) FROM MEMBER m WHERE m.USER_ID IS NULL
)
AND EXISTS (SELECT 1 FROM USERS WHERE LOGIN_NAME = 'demo_member')
AND NOT EXISTS (
  SELECT 1 FROM MEMBER WHERE USER_ID = (SELECT USER_ID FROM USERS WHERE LOGIN_NAME = 'demo_member')
);

-- 若仍无人绑定，则新建演示会员
INSERT INTO MEMBER (
  MEMBER_ID, NAME, PHONE_NUMBER, MEMBER_LEVEL, GENDER, REGISTER_DATE, STATUS, USER_ID
)
